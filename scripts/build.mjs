#!/usr/bin/env node
/**
 * dsh-recover-context build — zero runtime npm dependencies for the host
 * half (every @deepseek-ai/* contract is type-only or reached through the
 * cordis context, so nothing needs to be installed beside the dev toolchain),
 * and the client half is a single closure bundle in the web boot handoff
 * format.
 *
 * Produces the npm-package artifacts under lib/:
 *   lib/index.js  — host half: src/host/ bundled to plain ESM.
 *   lib/client.js — client half: src/client/ bundled to CJS, then wrapped in
 *                   `window.__ModuleLoader__.load({ id, factory })` — the
 *                   closure-factory format every `dsh.client` package's
 *                   `./client` export must use. React (and react/jsx-runtime)
 *                   arrive through the injected `require`, so they stay
 *                   external and become bare requires inside the factory.
 */
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'))

await mkdir(join(ROOT, 'lib'), { recursive: true })

// ---- host half: bundled TS -> ESM (node platform; no externals) ----------
await build({
  entryPoints: [join(ROOT, 'src', 'host', 'index.ts')],
  outfile: join(ROOT, 'lib', 'index.js'),
  format: 'esm',
  platform: 'node',
  target: 'es2022',
  bundle: true,
  sourcemap: false,
})

// ---- client half: bundled TS -> CJS, then wrap in the loader handoff ------
await build({
  entryPoints: [join(ROOT, 'src', 'client', 'index.ts')],
  outfile: join(ROOT, 'lib', '_client.js'),
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  bundle: true,
  external: ['react', 'react/jsx-runtime'],
  logOverride: { 'commonjs-variable-in-esm': 'silent' },
  sourcemap: false,
})
const clientSource = await readFile(join(ROOT, 'lib', '_client.js'), 'utf8')
await rm(join(ROOT, 'lib', '_client.js'))

const bundle = [
  '/* dsh-recover-context client bundle — generated by scripts/build.mjs from src/client/ */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(pkg.name)},`,
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  clientSource.replace(/\s+$/, '\n'),
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')
await writeFile(join(ROOT, 'lib', 'client.js'), bundle)

// ---- smoke checks ----
new Function(bundle) // syntax parse only; never executes (window is undefined here)
const host = await import(join(ROOT, 'lib', 'index.js'))
if (host.name !== 'dsh-recover-context' || !Array.isArray(host.inject) || typeof host.apply !== 'function') {
  throw new Error('host half does not expose the expected plugin shape (name/inject/apply)')
}
if (!host.inject.includes('webServer') || !host.inject.includes('sessions')) {
  throw new Error('host half must inject webServer and sessions')
}

console.log(`built ${pkg.name}:`)
console.log('  lib/index.js  (host half, ESM)')
console.log('  lib/client.js (client half, __ModuleLoader__ closure bundle)')
